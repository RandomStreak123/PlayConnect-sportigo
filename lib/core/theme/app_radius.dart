/// Centralized border-radius constants for the Sportigo design system.
///
/// Use these values instead of hardcoded BorderRadius.circular() numbers
/// throughout the app.
class AppRadius {
  AppRadius._();

  /// 4.0 — Micro: tiny badges, status indicators
  static const double xxs = 4.0;

  /// 8.0 — Small: skill chips, organizer badges
  static const double xs = 8.0;

  /// 12.0 — Medium-small: form fields, dropdowns, small cards
  static const double sm = 12.0;

  /// 16.0 — Medium: standard cards, buttons, containers
  static const double md = 16.0;

  /// 24.0 — Large: large cards, match cards, profile sections
  static const double lg = 24.0;

  /// 32.0 — Extra-large: profile cards, modal sheets
  static const double xl = 32.0;

  /// 100.0 — Full pill: sport filter chips, slot chips, rounded tags
  static const double pill = 100.0;
}

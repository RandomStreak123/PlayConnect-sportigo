/// Centralized icon size constants for the Sportigo design system.
///
/// Use these values instead of hardcoded numbers for all Icon(size:)
/// and IconButton(iconSize:) throughout the app.
class AppIconSize {
  AppIconSize._();

  /// 16 — Extra-small: badge icons, verification checkmarks, tiny decorative icons
  static const double xs = 16.0;

  /// 20 — Small: list row icons, settings row icons, notification icons
  static const double sm = 20.0;

  /// 24 — Medium (default): app bar icons, nav bar icons, action buttons, FABs
  static const double md = 24.0;

  /// 32 — Large: featured action icons, prominent sport icons
  static const double lg = 32.0;

  /// 48 — Extra-large: error state illustrations
  static const double xl = 48.0;

  /// 64 — Hero: empty state icons, onboarding illustrations
  static const double hero = 64.0;
}

/// Centralized spacing constants for the Sportigo design system.
///
/// Use these values instead of hardcoded numbers for all padding,
/// margin, and gap values throughout the app.
class AppSpacing {
  AppSpacing._();

  /// 4.0 — Micro gap: badge borders, tiny separators
  static const double xxs = 4.0;

  /// 8.0 — Small gap: icon padding, tight rows, avatar borders
  static const double xs = 8.0;

  /// 12.0 — Medium-small gap: card-to-card gaps, list row separators
  static const double sm = 12.0;

  /// 16.0 — Base unit: card inner padding, section row padding, list item margin
  static const double md = 16.0;

  /// 24.0 — Section gap: screen body padding, major section spacing, CTA buttons
  static const double lg = 24.0;

  /// 32.0 — Large gap: empty state containers, horizontal screen padding when xl
  static const double xl = 32.0;

  /// 48.0 — Hero spacing: empty state padding, large section breaks
  static const double xxl = 48.0;

  /// 100.0 — Bottom scroll clearance for floating nav bar
  static const double bottomNavClearance = 100.0;
}
